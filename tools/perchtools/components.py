"""The component registrations Perch knows about, and the rebase check that catches new ones.

Every component Chromium registers in RegisterComponentsForUpdate() (registration.cc) has to be
classified by Perch: wrapped in `if (google)` by patches/perch/shell/privacy-components.patch, or kept.
build/component-registrations.txt lists the calls Perch has classified; a rebase that brings in a
call not on the list fails, naming it, so a new Google component never registers unnoticed.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

REGISTRATION_CC = Path("chrome/browser/component_updater/registration.cc")
KNOWN_FILE = Path("build/component-registrations.txt")
FUNCTION = "void RegisterComponentsForUpdate()"
# Register*Component, MaybeRegister*, Register*IfEnabled and Manage*Registration(s) calls.
# The namespace, if any, is captured so Perch's own calls (perch::...) can be left out.
CALL_RE = re.compile(r"(?<![\w:])((?:\w+::)*)(\w*Regist(?:er|ration)\w*)\s*\(")
HEADER = (
    "# The Register* calls in Chromium's RegisterComponentsForUpdate() (registration.cc) that Perch's\n"
    "# privacy-components.patch has classified (wrapped in `if (google)`, or kept). Generated by\n"
    "# `perch-build components update`; a rebase fails on any call not listed here.\n"
)


class ComponentsError(ValueError):
    pass


@dataclass(frozen=True)
class ComponentDiff:
    new: tuple[str, ...]
    gone: tuple[str, ...]


def _strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def _function_body(text: str) -> str:
    start = text.find(FUNCTION)
    if start < 0:
        raise ComponentsError(f"{REGISTRATION_CC} has no {FUNCTION}; Chromium moved it, so update components.py")
    open_brace = text.index("{", start)
    depth = 0
    for index in range(open_brace, len(text)):
        depth += {"{": 1, "}": -1}.get(text[index], 0)
        if depth == 0:
            return text[open_brace + 1:index]
    raise ComponentsError(f"{FUNCTION} in {REGISTRATION_CC} never closes")


def registration_calls(text: str) -> list[str]:
    """The distinct Register* calls in RegisterComponentsForUpdate(), sorted. Calls Perch adds itself
    (perch::...) are not Chromium's, so they are left out."""
    calls = CALL_RE.findall(_function_body(_strip_comments(text)))
    return sorted({name for namespace, name in calls if not namespace.startswith("perch::")})


def read_registration(src: Path) -> str:
    path = src / REGISTRATION_CC
    if not path.is_file():
        raise ComponentsError(f"{path} is missing; run perch-build checkout first")
    return path.read_text()


def read_known(repo: Path) -> list[str]:
    path = repo / KNOWN_FILE
    if not path.is_file():
        raise ComponentsError(f"{KNOWN_FILE} is missing; run perch-build components update")
    lines = (line.strip() for line in path.read_text().splitlines())
    return [line for line in lines if line and not line.startswith("#")]


def render_known(calls: list[str]) -> str:
    return HEADER + "".join(f"{call}\n" for call in sorted(set(calls)))


def write_known(repo: Path, src: Path) -> Path:
    path = repo / KNOWN_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_known(registration_calls(read_registration(src))))
    return path


def check_components(repo: Path, src: Path) -> ComponentDiff:
    found = set(registration_calls(read_registration(src)))
    known = set(read_known(repo))
    return ComponentDiff(new=tuple(sorted(found - known)), gone=tuple(sorted(known - found)))


def new_component_reasons(diff: ComponentDiff) -> list[str]:
    """One reason per call the component filter has never classified."""
    return [
        f"registration.cc calls {name}, which Perch has not classified; wrap it in `if (google)` in "
        f"patches/perch/shell/privacy-components.patch or decide to keep it, then run perch-build components update"
        for name in diff.new
    ]
